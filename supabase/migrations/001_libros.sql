CREATE TABLE IF NOT EXISTS public.libros (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titulo TEXT NOT NULL,
 autor TEXT NOT NULL,
 anio INTEGER NOT NULL,
 CONSTRAINT libros_titulo_valido CHECK (length(btrim(titulo)) > 0),
 CONSTRAINT libros_autor_valido CHECK (length(btrim(autor)) > 0),
 CONSTRAINT libros_anio_valido CHECK (anio BETWEEN 1 AND 2100)
);
ALTER TABLE public.libros ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.libros FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA public TO authenticated;
GRANT SELECT, INSERT, DELETE ON TABLE public.libros TO authenticated;
DROP POLICY IF EXISTS "libros_select_authenticated" ON public.libros;
DROP POLICY IF EXISTS "libros_insert_authenticated" ON public.libros;
DROP POLICY IF EXISTS "libros_delete_authenticated" ON public.libros;
CREATE POLICY "libros_select_authenticated" ON public.libros FOR SELECT TO authenticated USING (true);
CREATE POLICY "libros_insert_authenticated" ON public.libros FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "libros_delete_authenticated" ON public.libros FOR DELETE TO authenticated USING (true);
